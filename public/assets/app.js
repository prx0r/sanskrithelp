/* ---------------------------------------------------------------- render */
function cell(vib, vac) {
  const p = state.familyDoc?.stems?.[state.stem]?.paradigm;
  return p?.[vib]?.[vac] || { status: 'MACHINE_GAP' };
}

/* The underlying sup ending the engine selected, read from the 4.1.2 step.
   We show it raw (sum̐, ṅas, ṭā …) because that is what the engine chose. */
function affixOf(c) {
  if (!c) return '';
  if (c.sup) return c.sup;
  if (!Array.isArray(c.steps)) return '';
  const step = c.steps.find(([code]) => code === '4.1.2');
  if (!step) return '';
  const parts = String(step[1] || '').split('+').map((s) => s.trim()).filter(Boolean);
  return parts.length > 1 ? parts[parts.length - 1] : '';
}

function render() {
  renderMatrix();
  renderOutput();
  renderTrace();
  renderGame();
}

function renderMatrix() {
  if (state.level < 3) { renderStemPreview(); return; }
  const showAffix = state.level >= 4;
  const showWord = true;
  let html = '';
  for (const v of VIB()) {
    html += `<div class="mrow">
      <button class="mcase ${state.vib === v.id ? 'on' : ''}" data-vib="${v.id}" data-layer="affix">
        <b class="dev">${esc(v.deva)}</b><small>${esc(v.en)}</small>
        <span class="mq">${esc(v.question)}</span>
      </button>`;
    for (const w of VAC()) {
      const c = cell(v.id, w.id);
      const on = state.vib === v.id && state.vac === w.id;
      if (c.status !== 'DERIVED') {
        html += `<button class="mcell blocked ${on ? 'on' : ''}" data-vib="${v.id}" data-vac="${w.id}"
          data-layer="blocked"><span class="dev">—</span><small>blocked</small></button>`;
        continue;
      }
      const hide = (state.mode === 'generate' || state.mode === 'reverse') && !state.revealed && on;
      const txt = showWord ? (hide ? '••••' : esc(c.iast)) : '<span class="q">?</span>';
      const dev = showWord ? (hide ? '••••' : esc(c.deva)) : '<span class="q">?</span>';
      const sup = showAffix ? affixOf(c) : '';
      html += `<button class="mcell ${on ? 'on' : ''}" data-vib="${v.id}" data-vac="${w.id}" data-layer="surface">
        <span class="dev">${dev}</span><small>${txt}</small>
        ${sup ? `<span class="affix-tag">${esc(sup)}</span>` : ''}
      </button>`;
    }
    html += '</div>';
  }
  $('#matrix').innerHTML = html;
  $$('.mcase').forEach((b) => b.addEventListener('click', () => { state.vib = b.dataset.vib; state.revealed = false; render(); }));
  $$('.mcell').forEach((b) => b.addEventListener('click', () => {
    state.vib = b.dataset.vib; state.vac = b.dataset.vac; state.revealed = false; render();
  }));
}

