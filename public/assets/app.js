const $ = (s) => document.querySelector(s);

const S = {
  index: null, verbs: null, cases: null, karaka: null,
  famCache: {},
  track: 'noun',
  railTab: 'family',      // noun: family|case   verb: tense|root
  filter: null,           // family id | case id | tense id | root id
  mode: 'family',
  q: null,
  answered: false,
  stats: null,
};

const SKEY = 'prakriya-v3';

/* ---------- stats ---------- */
function loadStats() {
  try {
    const s = JSON.parse(localStorage.getItem(SKEY) || '{}');
    return { streak: s.streak | 0, total: s.total | 0, right: s.right | 0, fam: s.fam || {} };
  } catch { return { streak: 0, total: 0, right: 0, fam: {} }; }
}
function saveStats() { try { localStorage.setItem(SKEY, JSON.stringify(S.stats)); } catch {} }

/* ---------- text ---------- */
const NFC = (s) => String(s || '').normalize('NFC').trim().replace(/\s+/g, ' ');
const low = (s) => NFC(s).toLowerCase();
const strip = (s) => low(s).normalize('NFD').replace(/[\u0300-\u036f]/g, '')
  .replace(/[’']/g, '').replace(/[^a-z0-9 ]/g, '').replace(/\s+/g, ' ').trim();
const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) =>
  ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));

function diffMarks(got, want) {
  const a = [...low(got)], b = [...low(want)];
  const m = a.length, n = b.length;
  const dp = Array.from({ length: m + 1 }, () => new Int32Array(n + 1));
  for (let i = m - 1; i >= 0; i--)
    for (let j = n - 1; j >= 0; j--)
      dp[i][j] = a[i] === b[j] ? dp[i + 1][j + 1] + 1 : Math.max(dp[i + 1][j], dp[i][j + 1]);
  const marks = new Array(m).fill(false);
  let i = 0, j = 0;
  while (i < m && j < n) {
    if (a[i] === b[j]) { marks[i] = true; i++; j++; }
    else if (dp[i + 1][j] >= dp[i][j + 1]) i++;
    else j++;
  }
  return marks;
}

/* ---------- data ---------- */
async function getJSON(path, cacheKey) {
  if (cacheKey && S[cacheKey]) return S[cacheKey];
  const r = await fetch(path);
  const d = await r.json();
  if (cacheKey) S[cacheKey] = d;
  return d;
}
async function loadFamily(id) {
  if (S.famCache[id]) return S.famCache[id];
  const f = S.index.families.find((x) => x.id === id);
  const d = await getJSON(f.file);
  S.famCache[id] = d;
  return d;
}
async function loadVerbs() {
  if (!S.verbs) S.verbs = await getJSON('data/verbs.json');
  return S.verbs;
}

const pick = (a) => a[Math.floor(Math.random() * a.length)];

/* ---------- pools ---------- */
function stemPool() {
  let s = S.index.stems;
  if (S.railTab === 'family' && S.filter) s = s.filter((x) => x.family === S.filter);
  return s.length ? s : S.index.stems;
}
function caseSlot() {
  const vib = S.railTab === 'case' && S.filter
    ? S.index.vibhakti.find((v) => v.id === S.filter) || pick(S.index.vibhakti)
    : pick(S.index.vibhakti);
  return { vib, vac: pick(S.index.vacana) };
}
function verbPool() {
  const v = S.verbs;
  let roots = v.roots;
  if (S.railTab === 'root' && S.filter) roots = roots.filter((r) => r.id === S.filter);
  return roots.length ? roots : v.roots;
}
function tensePool() {
  const v = S.verbs;
  if (S.railTab === 'tense' && S.filter) {
    const t = v.lakara.filter((x) => x.id === S.filter);
    if (t.length) return t;
  }
  return v.lakara;
}

/* ---------- questions ---------- */
async function makeQuestion() {
  return S.track === 'noun' ? makeNoun() : makeVerb();
}

async function makeNoun() {
  const stem = pick(stemPool());
  const family = S.index.families.find((f) => f.id === stem.family);
  const mode = S.mode === 'mix' ? pick(['family', 'build', 'reverse']) : S.mode;

  if (mode === 'family') {
    return { track: 'noun', mode, stem, family, colour: family.colour,
             ask: 'Which family does this stem belong to?', answer: family.label };
  }

  const doc = await loadFamily(stem.family);
  const { vib, vac } = caseSlot();
  const c = doc.stems[stem.id].paradigm[vib.id][vac.id];
  if (c.status !== 'DERIVED') return makeNoun();

  if (mode === 'build') {
    return { track: 'noun', mode, stem, family, vib, vac, cell: c, doc,
             colour: family.colour, answer: c.iast,
             ask: `Give the ${vib.en} ${vac.en}` };
  }

  const analyses = [];
  const p = doc.stems[stem.id].paradigm;
  for (const [v, row] of Object.entries(p))
    for (const [w, cc] of Object.entries(row))
      if (cc.status === 'DERIVED' && low(cc.iast) === low(c.iast)) analyses.push([v, w]);

  return { track: 'noun', mode: 'reverse', stem, family, vib, vac, cell: c, doc,
           colour: family.colour, answer: c.iast, analyses,
           ask: 'Which case and number is this form?' };
}

async function makeVerb() {
  await loadVerbs();
  const v = S.verbs;
  const root = pick(verbPool());
  const lak = pick(tensePool());
  const pu = pick(v.purusha);
  const va = pick(v.vacana);
  const c = v.paradigms[root.id][lak.id][`${pu.id}.${va.id}`];
  if (!c || c.status !== 'DERIVED') return makeVerb();

  const mode = S.mode === 'mix' ? pick(['build', 'tense']) : S.mode;

  if (mode === 'tense') {
    return { track: 'verb', mode, root, lak, pu, va, cell: c,
             colour: lak.colour, answer: lak.en,
             ask: 'Which tense is this form?' };
  }
  return { track: 'verb', mode: 'build', root, lak, pu, va, cell: c,
           colour: lak.colour, answer: c.iast,
           ask: `Give the ${lak.en} · ${pu.en} person ${va.en}` };
}

/* ---------- grading ---------- */
const VIB_ALIAS = {
  prathama: ['prathama', 'nominative', 'nom'], dvitiya: ['dvitiya', 'accusative', 'acc', 'obj'],
  tritiya: ['tritiya', 'instrumental', 'instr', 'inst'], caturthi: ['caturthi', 'dative', 'dat'],
  pancami: ['pancami', 'ablative', 'abl'], sasthi: ['sasthi', 'genitive', 'gen'],
  saptami: ['saptami', 'locative', 'loc'], sambodhana: ['sambodhana', 'vocative', 'voc'],
};
const VAC_ALIAS = {
  eka: ['eka', 'ekavacana', 'singular', 'sg'], dvi: ['dvi', 'dvivacana', 'dual', 'du'],
  bahu: ['bahu', 'bahuvacana', 'plural', 'pl'],
};
const LAK_ALIAS = {
  lat: ['lat', 'present', 'pres'], lan: ['lan', 'past', 'imperfect', 'imperf'],
  lrt: ['lrt', 'future', 'fut'], lot: ['lot', 'imperative', 'imper'],
  vidhilin: ['vidhilin', 'optative', 'opt'],
};

function classify(text, table, idKey) {
  const t = ' ' + strip(text) + ' ';
  for (const [id, al] of Object.entries(table))
    if (al.some((a) => t.includes(' ' + a + ' '))) return id;
  return null;
}

function familyMatch(input) {
  const t = strip(input);
  if (!t) return false;
  const fams = S.index.families;
  if (fams.some((f) => strip(f.label) === t || strip(f.id) === t)) return true;
  if (t.length >= 5) {
    const hits = fams.filter((f) => strip(f.label).includes(t) || t.includes(strip(f.label)));
    if (hits.length === 1) return true;
  }
  const pool = new Set(stemPool().map((s) => s.family));
  const cand = fams.filter((f) => pool.has(f.id) && strip(f.label).includes(t));
  return t.split(' ').length === 1 && cand.length === 1;
}

function grade(q, input) {
  if (!NFC(input)) return 'bad';
  if (q.mode === 'family') return familyMatch(input) ? 'ok' : 'bad';
  if (q.track === 'verb' && q.mode === 'tense') {
    return classify(input, LAK_ALIAS) === q.lak.id ? 'ok' : 'bad';
  }
  if (q.mode === 'reverse') {
    const vib = classify(input, VIB_ALIAS);
    const vac = classify(input, VAC_ALIAS);
    if (!vib || !vac) return 'bad';
    return q.analyses.some(([v, w]) => v === vib && w === vac) ? 'ok' : 'bad';
  }
  // typed form
  if (low(input) === low(q.answer)) return 'ok';
  if (strip(input) && strip(input) === strip(q.answer)) return 'loose';
  return 'bad';
}

/* ---------- render ---------- */
function setColour(hex) { document.documentElement.style.setProperty('--fc', hex); }

const MODES = {
  noun: [['family', 'Family', 'name the class'], ['build', 'Build', 'type the form'],
         ['reverse', 'Reverse', 'name the case'], ['mix', 'Mix', 'everything']],
  verb: [['build', 'Build', 'type the form'], ['tense', 'Tense', 'name the tense'],
         ['mix', 'Mix', 'both']],
};

function renderModes() {
  const list = MODES[S.track];
  if (!list.some(([id]) => id === S.mode)) S.mode = list[0][0];
  $('#modes').innerHTML = list.map(([id, b, s]) =>
    `<button class="mode ${id === S.mode ? 'on' : ''}" data-mode="${id}"><b>${b}</b><small>${s}</small></button>`).join('');
}

function renderRailTabs() {
  const tabs = S.track === 'noun'
    ? [['family', 'Families'], ['case', 'Cases']]
    : [['tense', 'Tenses'], ['root', 'Roots']];
  $('#railtabs').innerHTML = tabs.map(([id, label]) =>
    `<button class="rt ${id === S.railTab ? 'on' : ''}" data-tab="${id}">${label}</button>`).join('');
}

function accOf(key) {
  const f = S.stats.fam[key];
  return f && f.t ? Math.round((f.r / f.t) * 100) : null;
}

function renderRail() {
  renderRailTabs();
  const host = $('#famlist');
  const items = [];
  if (S.track === 'noun' && S.railTab === 'family') {
    for (const f of S.index.families)
      items.push({ key: f.id, label: f.label, sub: `${f.stems.length} stem${f.stems.length > 1 ? 's' : ''}`, colour: f.colour });
  } else if (S.track === 'noun') {
    for (const v of S.index.vibhakti)
      items.push({ key: v.id, label: v.en, sub: v.sanskrit, colour: '#7aa2c9' });
  } else if (S.railTab === 'tense') {
    for (const l of S.verbs?.lakara || [])
      items.push({ key: l.id, label: l.en, sub: l.deva, colour: l.colour });
  } else {
    for (const r of S.verbs?.roots || [])
      items.push({ key: r.id, label: r.iast, sub: r.gloss, colour: '#8fb4dc' });
  }

  host.innerHTML = items.map((it) => {
    const a = accOf(it.key);
    return `<button class="fam ${S.filter === it.key ? 'on' : ''}" style="--fc:${it.colour}" data-key="${it.key}">
      <span class="dot"></span>
      <span class="fl"><b>${esc(it.label)}</b><small>${esc(it.sub)}</small></span>
      <span class="pct">${a === null ? '' : a + '%'}</span>
      <span class="bar"><i style="width:${a === null ? 0 : a}%"></i></span>
    </button>`;
  }).join('');
}

function renderLegend() {
  const host = $('#legend');
  if (S.track === 'noun') {
    host.innerHTML = S.index.families.map((f) =>
      `<li><i style="background:${f.colour}"></i><b>${esc(f.label)}</b><span class="lw">${esc(f.deva)}</span></li>`).join('');
  } else {
    host.innerHTML = (S.verbs?.lakara || []).map((l) =>
      `<li><i style="background:${l.colour}"></i><b>${esc(l.en)}</b><span class="lw">${esc(l.deva)}</span></li>`).join('');
  }
}

function renderPrompt(q) {
  setColour(q.colour);
  if (q.track === 'noun') {
    const showForm = q.mode === 'reverse';
    $('#p-deva').textContent = showForm ? q.cell.deva : q.stem.deva;
    $('#p-iast').textContent = showForm ? q.cell.iast : q.stem.iast;
    $('#p-gloss').textContent = q.stem.gloss;
  } else {
    const showForm = q.mode === 'tense';
    $('#p-deva').textContent = showForm ? q.cell.deva : q.root.deva;
    $('#p-iast').textContent = showForm ? q.cell.iast : q.root.iast;
    $('#p-gloss').textContent = q.root.gloss;
  }
  $('#p-ask').textContent = q.ask;

  const tags = [];
  if (q.track === 'noun') {
    if (q.mode === 'family') tags.push('<span class="tag">type the family, or click its colour</span>');
    if (q.mode === 'build') {
      tags.push(`<span class="tag case">${q.vib.en}</span>`);
      tags.push(`<span class="tag num">${q.vac.en}</span>`);
      tags.push(`<span class="tag">${q.vib.question}</span>`);
    }
    if (q.mode === 'reverse') tags.push('<span class="tag">more than one answer may be right</span>');
  } else {
    if (q.mode === 'build') {
      tags.push(`<span class="tag case">${q.lak.en}</span>`);
      tags.push(`<span class="tag num">${q.pu.en} person</span>`);
      tags.push(`<span class="tag num">${q.va.en}</span>`);
    } else {
      tags.push(`<span class="tag">${q.pu.en} person · ${q.va.en}</span>`);
    }
  }
  $('#p-tags').innerHTML = tags.join('');
}

function renderStageGrid(q, revealed) {
  const host = $('#stagegrid');

  // family question: colour pad of every family
  if (q.mode === 'family') {
    host.innerHTML = `<div class="fampad">` + S.index.families.map((f) =>
      `<button data-fam="${f.id}" style="--fc:${f.colour}">
         <span class="sw" style="background:${f.colour}"></span>${esc(f.label)}</button>`).join('') + `</div>`;
    host.querySelectorAll('[data-fam]').forEach((b) => b.addEventListener('click', () => {
      if (S.answered) return;
      $('#input').value = S.index.families.find((f) => f.id === b.dataset.fam).label;
      check();
    }));
    return;
  }

  if (q.track === 'noun') {
    const p = q.doc.stems[q.stem.id].paradigm;
    let html = '<div class="sg noun"><div class="h"></div>' +
      S.index.vacana.map((w) => `<div class="h">${w.en.slice(0, 3)}</div>`).join('');
    for (const v of S.index.vibhakti) {
      html += `<div class="rh">${v.en.slice(0, 5)}</div>`;
      for (const w of S.index.vacana) {
        const c = p[v.id]?.[w.id];
        const isTarget = q.mode === 'build'
          ? (v.id === q.vib.id && w.id === q.vac.id)
          : (q.analyses || []).some(([a, b]) => a === v.id && b === w.id);
        if (!c || c.status !== 'DERIVED') { html += `<div class="c b">—</div>`; continue; }
        if (isTarget && !revealed) html += `<div class="c target hidden"><span class="d">?</span></div>`;
        else if (isTarget && revealed) html += `<div class="c solved"><span class="d">${esc(c.deva)}</span><span class="i">${esc(c.iast)}</span></div>`;
        else html += `<div class="c"><span class="d">${esc(c.deva)}</span><span class="i">${esc(c.iast)}</span></div>`;
      }
    }
    html += '</div><div class="sg-hint">' +
      (revealed ? 'the target cell is in colour' : 'every neighbour is given — work out the one marked ?') + '</div>';
    host.innerHTML = html;
    return;
  }

  // verb: 3 × 3 for this root + tense
  const slot = S.verbs.paradigms[q.root.id][q.lak.id];
  let html = '<div class="sg verb"><div class="h"></div>' +
    S.verbs.vacana.map((w) => `<div class="h">${w.en.slice(0, 3)}</div>`).join('');
  for (const pu of S.verbs.purusha) {
    html += `<div class="rh">${pu.en} per</div>`;
    for (const va of S.verbs.vacana) {
      const c = slot[`${pu.id}.${va.id}`];
      const isTarget = pu.id === q.pu.id && va.id === q.va.id;
      if (!c || c.status !== 'DERIVED') { html += `<div class="c b">—</div>`; continue; }
      if (isTarget && !revealed) html += `<div class="c target hidden"><span class="d">?</span></div>`;
      else if (isTarget && revealed) html += `<div class="c solved"><span class="d">${esc(c.deva)}</span><span class="i">${esc(c.iast)}</span></div>`;
      else html += `<div class="c"><span class="d">${esc(c.deva)}</span><span class="i">${esc(c.iast)}</span></div>`;
    }
  }
  html += `</div><div class="sg-hint">${esc(q.root.iast)} · ${esc(q.lak.en)} — ` +
    (revealed ? 'target in colour' : 'find the ? cell') + '</div>';
  host.innerHTML = html;
}

function renderTrace(q) {
  const box = $('#trace');
  const c = q.cell;
  if (!c) {
    box.innerHTML = `<div class="tr" data-r="class"><span class="c">class</span>
      <span>${esc(q.family.label)}</span><span class="a">${esc(q.family.deva)} · ${esc(q.family.note)}</span></div>`;
    return;
  }
  box.innerHTML = (c.steps || []).map(([code, after, role]) => {
    const txt = (S.index.sutra_map || {})[code] || '';
    return `<div class="tr" data-r="${role}"><span class="c">${esc(code)}</span>
      <span>${esc(txt)}</span><span class="a">${esc(after)}</span></div>`;
  }).join('');
}

function renderFeedback(q, verdict, input) {
  $('#fb-empty').hidden = true;
  $('#fb-body').hidden = false;

  const v = $('#verdict');
  v.className = 'verdict ' + (verdict === 'bad' ? 'bad' : 'ok');
  v.textContent = verdict === 'ok' ? 'Correct' : verdict === 'loose' ? 'Close — diacritics' : 'Not quite';

  if (q.mode === 'family') {
    $('#correct').innerHTML = `<span>${esc(q.family.label)}</span>`;
    $('#yours').innerHTML = `<span class="lbl">you wrote</span>${input ? esc(input) : '—'}`;
  } else if (q.mode === 'tense') {
    $('#correct').innerHTML = `<span>${esc(q.lak.en)}</span><span class="ci">${esc(q.lak.deva)}</span>`;
    $('#yours').innerHTML = `<span class="lbl">full form</span><span class="dev">${esc(q.cell.deva)}</span> ${esc(q.cell.iast)}`;
  } else if (q.mode === 'reverse') {
    const list = q.analyses.map(([a, b]) => {
      const V = S.index.vibhakti.find((x) => x.id === a);
      const W = S.index.vacana.find((x) => x.id === b);
      return `${V.en} ${W.en}`;
    }).join(' · ');
    $('#correct').innerHTML = `<span class="dev">${esc(q.cell.deva)}</span><span class="ci">${esc(q.cell.iast)}</span>`;
    $('#yours').innerHTML = `<span class="lbl">${q.analyses.length > 1 ? 'all valid analyses' : 'valid analysis'}</span>${esc(list)}`;
  } else {
    $('#correct').innerHTML = `<span class="dev">${esc(q.cell.deva)}</span><span class="ci">${esc(q.cell.iast)}</span>`;
    if (verdict === 'ok') {
      $('#yours').innerHTML = '';
    } else {
      const marks = diffMarks(input, q.answer);
      const chars = [...low(input)];
      const html = chars.map((ch, i) => `<span class="${marks[i] ? 'g' : 'w'}">${esc(ch)}</span>`).join('');
      $('#yours').innerHTML = `<span class="lbl">you wrote — struck letters are wrong</span>${html || '—'}`;
    }
  }

  renderTrace(q);
  $('#trace').hidden = true;
  $('#btn-why').textContent = 'why? show the derivation';
  $('#btn-why').hidden = false;
  $('#btn-next').hidden = false;
  $('#btn-check').hidden = true;
  $('#input').disabled = true;
}

function clearFeedback() {
  $('#fb-empty').hidden = false;
  $('#fb-body').hidden = true;
  $('#trace').hidden = true;
  $('#input').disabled = false;
  $('#btn-check').hidden = false;
  $('#btn-next').hidden = true;
  $('#btn-why').hidden = true;
}

/* ---------- flow ---------- */
async function newQuestion() {
  S.answered = false;
  S.q = await makeQuestion();
  clearFeedback();
  renderModes();
  renderRail();
  renderLegend();
  renderPrompt(S.q);
  renderStageGrid(S.q, false);
  $('#input').value = '';
  $('#input').placeholder =
    S.q.mode === 'family' ? 'short -a masculine'
      : S.q.mode === 'tense' ? 'present / past / future…'
      : S.q.mode === 'reverse' ? 'genitive singular'
      : 'type the form in roman';
  $('#hint').textContent = S.track === 'noun'
    ? `${S.railTab === 'case' && S.filter ? 'case: ' + S.filter : S.filter || 'all'} · ${stemPool().length} stems`
    : `${S.filter || 'all roots'} · ${S.verbs?.counts.forms || 0} verb forms`;
  $('#input').focus();
}

function check() {
  if (!S.q || S.answered) return;
  const input = $('#input').value;
  if (!NFC(input)) { $('#hint').textContent = 'Type something first.'; return; }
  const verdict = grade(S.q, input);

  S.answered = true;
  const st = S.stats;
  st.total++;
  const key = S.q.track === 'noun' ? S.q.family.id : S.q.lak.id;
  st.fam[key] = st.fam[key] || { t: 0, r: 0 };
  st.fam[key].t++;
  if (verdict === 'ok') { st.right++; st.streak++; st.fam[key].r++; } else st.streak = 0;
  saveStats(); paintStats(); renderRail();
  renderStageGrid(S.q, true);
  renderFeedback(S.q, verdict, input);
  $('#hint').textContent = verdict === 'ok'
    ? 'Correct — Enter for the next one.'
    : 'Read the breakdown, then press Enter.';
}

function paintStats() {
  const st = S.stats;
  $('#s-streak').textContent = st.streak;
  $('#s-acc').textContent = st.total ? Math.round((st.right / st.total) * 100) + '%' : '—';
}

/* ---------- wiring ---------- */
function wire() {
  $('#track').addEventListener('click', (e) => {
    const b = e.target.closest('.tk');
    if (!b) return;
    S.track = b.dataset.track;
    S.railTab = S.track === 'noun' ? 'family' : 'tense';
    S.filter = null;
    document.querySelectorAll('.tk').forEach((x) => x.classList.toggle('on', x === b));
    if (S.track === 'verb') loadVerbs().then(newQuestion);
    else newQuestion();
  });

  $('#modes').addEventListener('click', (e) => {
    const b = e.target.closest('.mode');
    if (!b) return;
    S.mode = b.dataset.mode;
    newQuestion();
  });

  $('#railtabs').addEventListener('click', (e) => {
    const b = e.target.closest('.rt');
    if (!b) return;
    S.railTab = b.dataset.tab;
    S.filter = null;
    renderRail();
  });

  $('#famlist').addEventListener('click', async (e) => {
    const b = e.target.closest('.fam');
    if (!b) return;

    // family question: clicking the family answers it
    if (S.q && S.q.mode === 'family' && !S.answered) {
      const fam = S.index.families.find((f) => f.id === b.dataset.key);
      if (fam) { $('#input').value = fam.label; check(); return; }
    }
    S.filter = S.filter === b.dataset.key ? null : b.dataset.key;
    renderRail();
    newQuestion();
  });

  $('#btn-check').onclick = check;
  $('#btn-next').onclick = newQuestion;
  $('#btn-all').onclick = () => { S.filter = null; renderRail(); newQuestion(); };

  $('#btn-why').onclick = () => {
    const t = $('#trace');
    t.hidden = !t.hidden;
    $('#btn-why').textContent = t.hidden ? 'why? show the derivation' : 'hide the derivation';
  };

  $('#btn-reset').onclick = () => {
    if (!confirm('Reset all progress on this device?')) return;
    S.stats = { streak: 0, total: 0, right: 0, fam: {} };
    saveStats(); paintStats(); renderRail();
  };

  $('#input').addEventListener('keydown', (e) => {
    if (e.key === 'Enter') { e.preventDefault(); S.answered ? newQuestion() : check(); }
    if (e.key === 'Escape') $('#input').value = '';
  });

  const KEYS = ['ā', 'ī', 'ū', 'ṛ', 'ñ', 'ṅ', 'ṇ', 'ś', 'ṣ', 'ṃ', 'ḥ', 'ṭ', 'ḍ'];
  $('#keys').innerHTML = KEYS.map((k) => `<button type="button">${k}</button>`).join('');
  $('#keys').addEventListener('click', (e) => {
    const b = e.target.closest('button');
    if (!b) return;
    const inp = $('#input');
    const s = inp.selectionStart ?? inp.value.length;
    const ep = inp.selectionEnd ?? s;
    inp.value = inp.value.slice(0, s) + b.textContent + inp.value.slice(ep);
    inp.focus();
    inp.setSelectionRange(s + 1, s + 1);
  });
}

