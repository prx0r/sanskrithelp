function renderTrace() {
  const c = cell(state.vib, state.vac);
  const stem = state.index.stems.find((s) => s.id === state.stem);
  const v = VIB().find((x) => x.id === state.vib);
  const w = VAC().find((x) => x.id === state.vac);
  const fam = state.index.families.find((f) => f.id === state.family);
  const body = $('#tracebody');

  if (c.status !== 'DERIVED') {
    body.innerHTML = `<div class="step blocked"><b>BLOCKED</b><div>The engine returned no derivation for ${esc(stem.iast)} · ${esc(v.en)} · ${esc(w.en)}. Nothing is substituted or guessed.</div></div>`;
    $('#trace-banner').textContent = '';
    return;
  }
  const maxLevel = state.level;
  const visible = (role) => {
    if (maxLevel >= 6) return true;
    if (maxLevel === 5) return role !== 'sound';
    if (maxLevel === 4) return ['stem', 'affix', 'surface'].includes(role);
    if (maxLevel === 3) return ['stem', 'affix', 'surface'].includes(role);
    return role === 'stem';
  };
  let html = `<div class="step" data-layer="stem"><span class="st-role">stem</span>
    <b class="dev">${esc(stem.deva)}</b> <span class="dim">${esc(stem.iast)} — ${esc(stem.gloss)}</span></div>
    <div class="step" data-layer="class"><span class="st-role">class</span>
    ${esc(fam.label)} · ${esc(stem.gender)}</div>
    <div class="step" data-layer="affix"><span class="st-role">affix</span>
    ${esc(v.en)} × ${esc(w.en)} → sup ending selected by 4.1.2</div>`;
  c.steps.forEach(([code, after, role]) => {
    if (!visible(role)) return;
    if (role === 'definition' && maxLevel < 5) return;
    const st = sutraText(code);
    html += `<div class="step" data-layer="${role}">
      <span class="st-role">${role}</span>
      <span class="sutra-code">${esc(code)}</span>
      <span class="sutra-txt dev">${esc(st)}</span>
      <span class="after">${esc(after)}</span>
    </div>`;
  });
  html += `<div class="step final" data-layer="surface"><span class="st-role">surface</span>
    <b class="dev">${esc(c.deva)}</b> <span class="iast">${esc(c.iast)}</span></div>`;
  body.innerHTML = html;
  $('#trace-banner').innerHTML =
    `<b>${c.steps.length} engine steps.</b> Every code above is a sūtra Vidyut actually fired for this word.
     Rung ${state.level} of 6 — raise the rung to reveal more.`;
}

/* ---------------------------------------------------------------- games */
function renderGame() {
  const box = $('#gamebox');
  const c = cell(state.vib, state.vac);
  const stem = state.index.stems.find((s) => s.id === state.stem);
  const v = VIB().find((x) => x.id === state.vib);
  const w = VAC().find((x) => x.id === state.vac);

  if (state.mode === 'explore') {
    box.innerHTML = `<button class="primary" id="reveal">${state.revealed ? 'Hide' : 'Reveal form + trace'}</button>`;
    $('#reveal')?.addEventListener('click', () => { state.revealed = !state.revealed; render(); });
    return;
  }

  if (state.mode === 'generate') {
    box.innerHTML = `
      <div class="lbl">Produce <b>${esc(v.en)} ${esc(w.en)}</b> of ${esc(stem.iast)} in IAST</div>
      <input type="text" id="guess" autocomplete="off" spellcheck="false" placeholder="type the form">
      <div class="keys" id="keys"></div>
      <button class="primary" id="check">Check</button>`;
    ['ā','ī','ū','ṛ','ñ','ṅ','ṇ','ś','ṣ','ṃ','ḥ','ṭ','ḍ'].forEach((ch) => {
      const b = document.createElement('button');
      b.textContent = ch;
      b.onclick = () => { const i = $('#guess'); i.value += ch; i.focus(); };
      $('#keys').appendChild(b);
    });
    $('#check').onclick = () => {
      const val = ($('#guess').value || '').trim();
      if (!val) return setStatus('Type a form first.', false);
      if (c.status !== 'DERIVED') return setStatus('That slot is blocked — nothing to match.', false);
      state.attempts++;
      const norm = (s) => s.normalize('NFC');
      const exact = norm(val) === norm(c.iast);
      const loose = strip(val) === strip(c.iast);
      if (exact || loose) {
        state.correct++;
        state.revealed = true;
        setStatus(exact ? 'Correct — exact IAST.' : 'Accepted without diacritics. Watch vowel length and ṃ/ḥ.', true);
      } else {
        state.revealed = true;
        setStatus(`Not quite. The engine gives “${c.iast}”. Look at the ${roleName(c)} row below.`, false);
      }
      paintScore();
      render();
    };
    $('#guess').addEventListener('keydown', (e) => { if (e.key === 'Enter') $('#check').click(); });
    return;
  }

  if (state.mode === 'reverse') {
    const form = c.status === 'DERIVED' ? c.iast : '';
    const readings = reverseFor(form);
    const want = readings.same;
    // Choices: every true reading of this form for this stem, plus two
    // decoy analyses of the same stem that are not true readings.
    const keyOf = ([, vv, ww]) => `${vv}|${ww}`;
    const trueKeys = new Set(want.map(keyOf));
    const decoys = [];
    for (const vv of VIB()) {
      for (const ww of VAC()) {
        const k = `${vv.id}|${ww.id}`;
        if (trueKeys.has(k) || decoys.length >= 2) continue;
        const alt = cell(vv.id, ww.id);
        if (alt.status === 'DERIVED' && alt.iast !== form) decoys.push([state.stem, vv.id, ww.id]);
        if (decoys.length >= 2) break;
      }
      if (decoys.length >= 2) break;
    }
    const choices = [...want, ...decoys];
    box.innerHTML = `
      <div class="lbl">Which analyses can <b class="iast">${esc(form)}</b> have
        <span class="dim">(of ${esc(state.stem)})</span>?</div>
      <div id="rev-choices" class="chips small"></div>
      <button class="primary" id="rev-check">Check</button>
      <div class="dim" id="rev-hint">Select every valid reading. Partial answers fail.</div>`;
    const chosen = new Set();
    $('#rev-choices').innerHTML = choices.length ? choices.map(([s, vv, ww]) => {
      const v2 = VIB().find((x) => x.id === vv);
      const w2 = VAC().find((x) => x.id === ww);
      return `<button class="chipbtn opt" data-key="${vv}|${ww}">${esc(v2.en)} ${esc(w2.en)}</button>`;
    }).join('') : '<span class="dim">no readings</span>';
    $$('.opt').forEach((b) => b.addEventListener('click', () => {
      const k = b.dataset.key;
      chosen.has(k) ? chosen.delete(k) : chosen.add(k);
      b.classList.toggle('on', chosen.has(k));
    }));
    $('#rev-check').onclick = () => {
      const ok = trueKeys.size === chosen.size && [...trueKeys].every((k) => chosen.has(k));
      state.attempts++;
      if (ok) state.correct++;
      state.revealed = true;
      paintScore();
      setStatus(ok
        ? 'Correct — every valid reading, and only those.'
        : `Not the full set. The engine allows: ${[...trueKeys].map((k) => k.replace('|', ' ')).join(', ')}.`,
        ok);
      renderTrace();
    };
    return;
  }

  // rule surgery
  box.innerHTML = `
    <div class="lbl">Which operation produces <b>${esc(v.en)} ${esc(w.en)}</b> of ${esc(stem.iast)}?</div>
    <div class="chips" id="ops"></div>
    <div class="dim" id="ops-hint">Predict the operation, not the finished word.</div>`;
  const ops = surgeryOptions(stem, v, w, c);
  $('#ops').innerHTML = ops.map((o) => `<button class="chipbtn op" data-k="${esc(o.key)}">${esc(o.label)}</button>`).join('');
  $$('.op').forEach((b) => b.addEventListener('click', () => {
    state.attempts++;
    const o = ops.find((x) => x.key === b.dataset.k);
    const ok = !!o.correct;
    if (ok) state.correct++;
    state.revealed = true;
    paintScore();
    setStatus(ok ? `Correct. ${o.why}` : `Not this one. ${o.why}`, ok);
    renderTrace();
  }));
}

function roleName(c) {
  const affix = c.steps.find(([, , r]) => r === 'operation');
  return affix ? 'operation' : 'affix';
}

function strip(s) {
  return String(s || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase().replace(/[^a-z]/g, '');
}

function reverseFor(form) {
  const doc = state.familyDoc;
  const all = [];
  const same = [];
  if (!form) return { all, same };
  for (const [sid, node] of Object.entries(doc.stems)) {
    for (const [vv, row] of Object.entries(node.paradigm)) {
      for (const [ww, cl] of Object.entries(row)) {
        if (cl.status === 'DERIVED' && cl.iast === form) {
          all.push([sid, vv, ww]);
          if (sid === state.stem) same.push([sid, vv, ww]);
        }
      }
    }
  }
  // reverse game is scoped to the selected stem, but distractors come from the family
  const opts = same.length ? dedupe([...all]) : all;
  return { all: opts, same: same.length ? same : all.filter(([s]) => s === state.stem) };
}

function dedupe(list) {
  const seen = new Set();
  return list.filter(([s, v, w]) => {
    const k = `${s}|${v}|${w}`;
    if (seen.has(k)) return false;
    seen.add(k);
    return true;
  });
}

function surgeryOptions(stem, v, w, c) {
  const ops = [];
  const thisAffix = (c.steps.find(([code]) => code === '4.1.2') || [])[1] || '';
  // real operations fired
  const real = c.steps.filter(([, , r]) => r === 'operation');
  const realCode = real.length ? real[real.length - 1][0] : '4.1.2';
  const realTxt = sutraText(realCode);
  ops.push({
    key: 'real', correct: true,
    label: `${realCode}${realTxt ? ' · ' + realTxt : ''}`,
    why: `That is the operation the engine fires: ${realCode}.`,
  });
  // plausible distractors from other families
  const pool = [
    ['7.1.12', 'ṭāṅasiṅasām inātsyāḥ — the -a stem substitution'],
    ['7.3.111', 'gher ṅiti — guṇa of a ghi stem'],
    ['7.3.113', 'yāḍ āpaḥ — the yāṭ augment'],
    ['7.2.111', 'īd ūd bhyāṃ — the nā augment'],
    ['6.1.78', 'eco ’yavāyāvaḥ — vowel coalescence to ay/av'],
    ['8.3.15', 'khar avasānayor visarjanīyaḥ — visarga'],
  ].filter(([code]) => code !== realCode);
  // pick two deterministic distractors
  const pick = pool.filter(([code]) => VIB().length && /^[0-9.]+$/.test(code));
  const seed = stem.id.length + v.id.length + w.id.length;
  const chosen = [pick[seed % pick.length], pick[(seed + 2) % pick.length]].filter(Boolean);
  for (const [code, label] of chosen) {
    ops.push({ key: code, correct: false, label: `${code} · ${label}`, why: `${code} belongs to a different family — it does not fire for ${stem.iast}.` });
  }
  return ops.sort((a, b) => (a.key === 'real' ? -1 : 0) - (b.key === 'real' ? -1 : 0) || a.key.localeCompare(b.key));
}

function setStatus(msg, ok) {
  const el = $('#status');
  el.textContent = msg;
  el.className = 'status ' + (ok ? 'ok' : 'bad');
}

function paintScore() {
  $('#score').textContent = state.attempts
    ? `${state.correct}/${state.attempts} correct`
    : '';
  $('#bar').style.width = state.attempts ? `${Math.round((state.correct / state.attempts) * 100)}%` : '0%';
}

/* ---------------------------------------------------------------- drill */
function buildDrill() {
  const stems = state.index.stems;
  const fam = state.index.families;
  const out = [];
  for (const s of stems) {
    const f = fam.find((x) => x.id === s.family);
    out.push({
      kind: 'class',
      q: `Which family does <b>${esc(s.iast)}</b> (${esc(s.gloss)}) belong to?`,
      answer: f.label,
      hint: s.note || '',
      layer: 'class',
    });
  }
  return out.slice(0, 40);
}

function renderDrill() {
  const qs = buildDrill();
  if (!qs.length) return;
  const idx = Math.floor(Math.random() * qs.length);
  const q = qs[idx];
  $('#drillbody').innerHTML = `
    <div class="dq">${q.q}</div>
    <input type="text" id="dq-input" placeholder="type the family label, e.g. short -a masculine">
    <button class="primary" id="dq-check">Check</button>
    <div class="status" id="dq-status"></div>
    <div class="dim" id="dq-hint"></div>`;
  $('#dq-check').onclick = () => {
    const val = ($('#dq-input').value || '').trim().toLowerCase();
    const ok = val && q.answer.toLowerCase().includes(val) || val === q.answer.toLowerCase();
    $('#dq-status').className = 'status ' + (ok ? 'ok' : 'bad');
    $('#dq-status').textContent = ok ? 'Correct.' : `Answer: ${q.answer}`;
    if (!ok && q.hint) $('#dq-hint').textContent = q.hint;
  };
  $('#dq-input').addEventListener('keydown', (e) => { if (e.key === 'Enter') $('#dq-check').click(); });
}

/* ---------------------------------------------------------------- wire */
$('#modes').addEventListener('click', (e) => {
  const b = e.target.closest('button');
  if (!b) return;
  state.mode = b.dataset.mode;
  state.revealed = false;
  setStatus('', true);
  render();
});

document.addEventListener('DOMContentLoaded', () => {
  boot().then(() => { renderDrill(); paintScore(); });
});
